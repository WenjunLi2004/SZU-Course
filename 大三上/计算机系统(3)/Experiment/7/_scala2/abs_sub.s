.text
    .global _start

_start:
    # ==========================
    # 测试用例 1: 正结果验证
    # 预期: |20 - 10| = 10 (0x0000000A)
    # ==========================
    
    # 1. 初始化寄存器 (x6=20, x7=10)
    addi x6, x0, 20     # 对应机器码: 01400313
    addi x7, x0, 10     # 对应机器码: 00A00393

    # 2. 执行 abs_sub x5, x6, x7
    # 汇编器不认识 abs_sub，我们用 nop 占位，稍后在 hex 中替换
    nop                 # <--- 替换点 A (把 00000013 换成 027342B3)

    # 3. 插入几个 nop 作为隔离，方便波形观察
    nop
    nop

    # ==========================
    # 测试用例 2: 负结果转正验证
    # 预期: |10 - 50| = 40 (0x00000028)
    # ==========================

    # 4. 重新赋值 (x6=10, x7=50)
    addi x6, x0, 10     # 对应机器码: 00A00313
    addi x7, x0, 50     # 对应机器码: 03200393

    # 5. 再次执行 abs_sub x5, x6, x7
    nop                 # <--- 替换点 B (把 00000013 换成 027342B3)

    # ==========================
    # 结束程序
    # ==========================
exit:
    j exit              # 死循环